static constexpr const char *kTitlesLog  = "fs:/vol/external01/wiiu/lostreavers_titles.log";
static constexpr const char *kPluginLog  = "fs:/vol/external01/wiiu/lostreavers/plugin.log";
// Title IDs Lost Reavers is known to run as (US/EU/JP and the user's install). Only used to add the SD content
// layer at launch, before the game reads its file table.
static constexpr uint64_t kKnownTitleIds[] = {0x00050000101A4800ULL, 0x00050000101A4900ULL, 0x00050000101A4A00ULL, 0x00050000101B9900ULL};

// Game addresses as linked (v16 RPX). The plugin adds the load offset.
static constexpr uint32_t kSetGameServerAddress = 0x02104b34;
static constexpr uint32_t kSetGameServerScheme  = 0x02104aa8;
static constexpr uint32_t kSetGameServerPort    = 0x02104bc0;
// PhaseServiceToken patch: absolute data addresses inside its code (flag word, token buffer).
static constexpr uint32_t kSvcFlag  = 0x1047c8cc;
static constexpr uint32_t kSvcToken = 0x1057127c;

// ---- Settings (fixed: Protarium server; override in inkay_config.local.h) -----------------------------------
#ifndef LOST_REAVERS_RELAY_IP
#define LOST_REAVERS_RELAY_IP 0x39819BC6u // 57.129.155.198
#endif
#ifndef LOST_REAVERS_RELAY_PORT
#define LOST_REAVERS_RELAY_PORT 8765
#endif
static bool sWritePatches = true;
static bool sSetServer    = true;
static bool sEnabled      = true;
static bool sLayerAdded   = false; // no patched-files layer in Inkay (Cemu-only)
static uint32_t sServerIp = LOST_REAVERS_RELAY_IP;
static int sServerPort    = LOST_REAVERS_RELAY_PORT;

static char16_t sHost[32];
static char16_t sScheme[] = u"http";
static void buildHost() {
    char buf[32];
    snprintf(buf, sizeof(buf), "%u.%u.%u.%u", (unsigned) (sServerIp >> 24) & 0xff, (unsigned) (sServerIp >> 16) & 0xff,
             (unsigned) (sServerIp >> 8) & 0xff, (unsigned) sServerIp & 0xff);
    size_t i = 0;
    for (; buf[i] && i < 31; i++) sHost[i] = (char16_t) buf[i];
    sHost[i] = 0;
}

// ---- Logging --------------------------------------------------------------------------------------------------
// No file access from inside the game's calls (it can hang the game or the console): lines are kept in memory
// and written when the game closes (ON_APPLICATION_ENDS).
static char sPBuf[6144];
static size_t sPLen = 0;
static char sTBuf[2048];
static size_t sTLen = 0;
static void bufLog(char *buf, size_t cap, size_t &len, const char *fmt, ...) {
    if (len + 2 >= cap) return;
    va_list ap;
    va_start(ap, fmt);
    int n = vsnprintf(buf + len, cap - len - 1, fmt, ap);
    va_end(ap);
    if (n < 0) return;
    len += ((size_t) n < cap - len - 1) ? (size_t) n : cap - len - 2;
    buf[len++] = '\n';
    buf[len]   = 0;
}
#define TLOG(...) bufLog(sTBuf, sizeof(sTBuf), sTLen, __VA_ARGS__)
#define PLOG(...) bufLog(sPBuf, sizeof(sPBuf), sPLen, __VA_ARGS__)
// A thread of the plugin's own writes new log lines to the SD card every 250 ms, so the log survives the game
// crashing (the last line shows how far it got). It never runs inside a game call.
static size_t sTDone = 0, sPDone = 0;
static bool sPFresh = true;
static void flushLogs() {
    size_t t = sTLen, p = sPLen;
    if (t > sTDone) {
        if (FILE *f = fopen(kTitlesLog, "a")) { fwrite(sTBuf + sTDone, 1, t - sTDone, f); fclose(f); }
        sTDone = t;
    }
    if (p > sPDone || sPFresh) {
        if (FILE *f = fopen(kPluginLog, sPFresh ? "w" : "a")) { fwrite(sPBuf + sPDone, 1, p - sPDone, f); fclose(f); }
        sPDone  = p;
        sPFresh = false;
    }
}
static OSThread sLogThread;
static uint8_t sLogStack[0x4000] __attribute__((aligned(16)));
static volatile bool sLogRun = false, sLogStarted = false;
static int logThreadMain(int, const char **) {
    while (sLogRun) {
        flushLogs();
        OSSleepTicks(OSMillisecondsToTicks(250));
    }
    flushLogs();
    return 0;
}
// Give the log thread time to write the last line (called from the game thread during startup only).
static void checkpoint() { OSSleepTicks(OSMillisecondsToTicks(300)); }
static void startLogThread() {
    if (sLogStarted) return;
    sTLen = sTDone = sPLen = sPDone = 0;
    sPFresh = true;
    sLogRun = true;
    if (OSCreateThread(&sLogThread, logThreadMain, 0, nullptr, sLogStack + sizeof(sLogStack), sizeof(sLogStack), 30,
                       OS_THREAD_ATTRIB_AFFINITY_CPU0 | OS_THREAD_ATTRIB_DETACHED)) {
        OSSetThreadName(&sLogThread, "LostReaversOfflineLog");
        OSResumeThread(&sLogThread);
        sLogStarted = true;
    }
}
static void stopLogThread() {
    if (!sLogStarted) return;
    sLogRun = false;
    OSSleepTicks(OSMillisecondsToTicks(400));
    sLogStarted = false;
}

