// Lost Reavers Online - Aroma plugin (plays on a community server; storage id, .wps and layer names keep "Offline").
// Applies the same patches as the Cemu graphic pack (cemu-pack/patch_offline.asm) to the running game, points
// the game at the offline Snow API server, and loads the patched game files from the SD card.
//
// How the game is found: nn::act::Initialize is hooked. The game calls it from one of 7 known places before any
// of the patched login/token steps; the return address of that call tells where the game's code is loaded
// (matched against the 4 instructions before each known call site), r13 tells where its data is. Every patch
// address is moved by those offsets, the words are checked against v16, and only then written.
//
//  * Instruction patches: src/patches.h (generated by tools/gen-plugin-patches.js).
//  * Server address: the game's own UObject::SetGameServerAddress/Scheme/Port are called with
//    http://<ip>:<port> from the plugin menu, and hooked so the game keeps them.
//  * Game files: sd:/wiiu/lostreavers/content is merged over /vol/content (the patched PH_Title.xxx etc).
//  * Logs: sd:/wiiu/lostreavers_titles.log (every start / hook call), sd:/wiiu/lostreavers/plugin.log.
