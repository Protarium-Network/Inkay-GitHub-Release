// ---- Game function replacements (same behaviour as the Cemu patches, installed with the FunctionPatcher) -------
// Writing game code word by word does not work on a console (the code pages are read-only; v0.10/v0.11 hung),
// so each patched function is replaced as a whole. Linked addresses; the load offset is added at install time.
#define W32(a) (*(volatile uint32_t *) (uintptr_t) (a))
static uint32_t sSvcFlagAddr = 0, sSvcTokenAddr = 0; // data addresses used by PhaseServiceToken, offset applied
static bool sPatchOk = false;

// OnlineWiiUNexSystemWiiU::LoginNetwork(ctx): report a finished NEX login (connected flags, context result 0).
DECL_FUNCTION(int, LR_LoginNetwork, uint32_t self, uint32_t ctx) {
    if (!ctx) return 7;
    W32(ctx + 0x48)    = 0;
    W32(self + 0x250)  = ctx;
    W32(self + 0x4a8)  = 1;
    W32(self + 0x4ac)  = 1;
    W32(self + 0x4b0)  = 0;
    return 0;
}
// OnlineWiiUNetSystemWiiU::PhaseServiceToken: store a stand-in service token instead of asking Nintendo
// (that request is what returns 102-2534 now that the game's online service has ended).
DECL_FUNCTION(int, LR_PhaseServiceToken, uint32_t self) {
    if (sSvcFlagAddr) W32(sSvcFlagAddr) = 1;
    W32(self + 0x4c0) = 1;
    if (sSvcTokenAddr) memcpy((void *) (uintptr_t) sSvcTokenAddr, "offline", 8);
    return 1;
}
